// Group matching neighbours: "Tue – Sat 9am – 5pm · Sun 9am – 2pm · Mon closed".
function hoursSummary(hours) {
  const order = [1, 2, 3, 4, 5, 6, 0];
  const label = (row) => (row.is_open ? displayTime(row.open_time) + ' – ' + displayTime(row.close_time) : 'closed');
  const groups = [];
  for (const day of order) {
    const text = label(hours[day]);
    const last = groups[groups.length - 1];
    if (last && last.text === text) last.to = day;
    else groups.push({ from: day, to: day, text });
  }
  const short = (day) => dayNames[day].slice(0, 3);
  return groups.map((group) => (group.from === group.to ? short(group.from) : short(group.from) + ' – ' + short(group.to)) + ' ' + group.text).join(' · ');
}

