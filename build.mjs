function structuredData() {
  const match = /^(.*?),\s*([^,]+?)\s+(SA|NSW|VIC|QLD|WA|TAS|NT|ACT)\s+(\d{4})$/i.exec(venue.address.replace(/\s*\n\s*/g, ', '));
  const address = match
    ? { '@type': 'PostalAddress', streetAddress: match[1], addressLocality: match[2], addressRegion: match[3].toUpperCase(), postalCode: match[4], addressCountry: 'AU' }
    : { '@type': 'PostalAddress', streetAddress: venue.address, addressCountry: 'AU' };
  const data = {
    '@context': 'https://schema.org',
    '@type': 'CafeOrCoffeeShop',
    name: venue.name,
    url: publicOrigin + '/',
    image: [publicOrigin + '/assets/client/acai-trio.jpg', publicOrigin + '/assets/graphic/family-instagram.webp'],
    telephone: venue.phone,
    ...(venue.email ? { email: venue.email } : {}),
    ...(venue.abn ? { taxID: venue.abn } : {}),
    address,
    servesCuisine: ['Açaí', 'Coffee', 'Smoothies'],
    menu: publicOrigin + '/menu/',
    acceptsReservations: true,
    sameAs: [instagramUrl],
    openingHoursSpecification: venue.hours.filter((row) => row.is_open).map((row) => ({
      '@type': 'OpeningHoursSpecification', dayOfWeek: 'https://schema.org/' + dayNames[row.day_of_week], opens: row.open_time, closes: row.close_time,
    })),
  };
  return '<script type="application/ld+json">' + JSON.stringify(data).replace(/</g, '\\u003c') + '</script>';
}

// Photos ship as responsive WebP (560, 800 and full width) with the original
// file as the fallback. Templates can set data-sizes for small placements.
function responsiveImages(html) {
  return html.replace(/<img\b[^>]*\ssrc="\/assets\/(client|graphic)\/([\w-]+)\.(jpg|webp)"[^>]*>/g, (tag, folder, name) => {
    const base = '/assets/' + folder + '/' + name;
    const full = name === 'family-instagram' ? 1100 : 1122;
    const widths = [560, 800, full];
    if (!widths.every((width) => existsSync('.' + base + '-' + width + '.webp'))) return tag;
    const sizes = /data-sizes="([^"]+)"/.exec(tag)?.[1] || '(max-width: 900px) 92vw, 46vw';
    const img = tag.replace(/\s*data-sizes="[^"]+"/, '');
    return '<picture><source type="image/webp" srcset="' + widths.map((width) => base + '-' + width + '.webp ' + width + 'w').join(', ') + '" sizes="' + sizes + '" />' + img + '</picture>';
  });
}

